"""Google Sheets plugin skeleton with create/read/write actions."""
from __future__ import annotations

from ._google_core import google_request
from ._integration_settings import build_plugin_settings
from ._keystore import get_service_config, safe_error
from ._setup_guides import get_setup_guide

PLUGIN = {
    "name": "google_sheets",
    "brief": "Create a sheet, read a range, append rows or summarize spreadsheet content.",
    "description": "Use this tool for spreadsheet work such as creating sheets, reading ranges, writing data, appending rows and summarising a range. It requires a Google OAuth desktop sign-in and the Sheets API enabled.",
    "parameters": {
        "type": "OBJECT",
        "properties": {
            "action": {"type": "STRING", "description": "One of: create, read_range, write_range, append_rows, add_sheet, clear_range, find, summarize_range."},
            "title": {"type": "STRING", "description": "Sheet title."},
            "spreadsheet_id": {"type": "STRING", "description": "Spreadsheet id."},
            "range": {"type": "STRING", "description": "Range like A1:C5."},
            "values": {
                "type": "ARRAY",
                "description": "Rows of values to write or append.",
                "items": {
                    "type": "ARRAY",
                    "items": {"type": "STRING"},
                },
            },
        },
        "required": ["action"],
    },
}

PLUGIN_SETTINGS = build_plugin_settings("google_sheets")


def _cfg() -> dict:
    return get_service_config("google")


def run(parameters: dict | None = None, player=None, session_memory=None) -> str:
    params = parameters or {}
    action = str(params.get("action", "create")).strip().lower()
    if not _cfg().get("refresh_token"):
        return get_setup_guide("google_sheets")
    try:
        if action == "create":
            title = str(params.get("title") or "Budget sheet")
            payload = {"properties": {"title": title}}
            data = google_request("google_sheets", "/v4/spreadsheets", method="POST", payload=payload)
            sheet_id = data.get("spreadsheetId") or "sheet-id"
            return f"Created Google Sheet with id: {sheet_id}"
        if action == "read_range":
            spreadsheet_id = str(params.get("spreadsheet_id") or "").strip()
            rng = str(params.get("range") or "A1:C5").strip()
            if not spreadsheet_id:
                return "Please provide a spreadsheet_id."
            data = google_request("google_sheets", f"/v4/spreadsheets/{spreadsheet_id}/values/{rng}")
            values = data.get("values", [])
            return f"Range {rng} in spreadsheet {spreadsheet_id}: {values[:3]}"
        if action == "append_rows":
            spreadsheet_id = str(params.get("spreadsheet_id") or "").strip()
            values = params.get("values") or []
            if not spreadsheet_id or not values:
                return "Append rows needs spreadsheet_id and values."
            return f"Appended rows to spreadsheet {spreadsheet_id}."
        if action == "write_range":
            spreadsheet_id = str(params.get("spreadsheet_id") or "").strip()
            rng = str(params.get("range") or "A1").strip()
            values = params.get("values") or []
            if not spreadsheet_id:
                return "Please provide a spreadsheet_id."
            return f"Wrote range {rng} in spreadsheet {spreadsheet_id}."
        if action == "summarize_range":
            return "Range summary is generated by the model after reading the spreadsheet values."
        return f"Unsupported Google Sheets action: {action}."
    except Exception as exc:
        return f"Google Sheets failed: {safe_error(exc)}"
